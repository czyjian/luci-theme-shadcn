// OpenClash's legacy luminanceFromColor() only understands hex/rgb.
// Give its body-background probe an equivalent sRGB value on OpenClash pages.
// Keep the theme's OKLCH tokens and OpenClash's own editor themes intact.
import Color from "colorjs.io";
import { writeFile } from "node:fs/promises";
import { resolveMode } from "../tokens/resolve.js";
const rgb = (mode) =>
  new Color(resolveMode(mode).background)
    .to("srgb")
    .toString({ format: "hex" });
await writeFile(
  new URL("../src/media/patches/admin-services-openclash.css", import.meta.url),
  `/* Generated by scripts/gen-openclash-compat.js; do not edit.\n * Issue #9: an RGB body background lets OpenClash correctly detect light/dark.\n * Values come from the original Shadcn background tokens. */\nbody[data-page^="admin-services-openclash"] {\n  background-color: ${rgb("light")};\n}\nhtml[data-darkmode="true"] body[data-page^="admin-services-openclash"] {\n  background-color: ${rgb("dark")};\n}\n`,
);
